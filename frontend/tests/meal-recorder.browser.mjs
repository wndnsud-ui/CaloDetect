// Isolated React fixture: no shared DB, real photos uploaded, or paid LLM calls.
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const browser=await chromium.launch({channel:'msedge',headless:true});
const base=process.env.PREVIEW_URL||'http://localhost:5174';
const file='frontend/public/rewards/products/salad_box/hero.jpg';
const calls=page=>page.evaluate(()=>window.__recorderCalls||[]);
const saved=async page=>JSON.parse(await page.getByTestId('saved').textContent());
async function analyze(page){
  await page.locator('input[type=file]').setInputFiles(file);
  const before=await calls(page);
  assert.equal(before.some(p=>p.includes('/meals/detect')),false,'Selecting a photo must not auto-analyze');
  await page.getByRole('button',{name:'사진 분석하기',exact:true}).click();
}
try{
  for(const width of [1440,390]){
    const page=await browser.newPage({viewport:{width,height:1000}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(`${base}/tests/meal-recorder.html`);
    assert.equal(await page.getByRole('button',{name:'사진 분석하기',exact:true}).isDisabled(),true);
    assert.equal(await page.getByRole('button',{name:'직접 입력하기',exact:false}).count(),1,'Manual entry is offered before any photo');
    assert.equal(await page.getByRole('button',{name:'AI로 영양 추정하기'}).count(),0);
    await analyze(page);
    await page.getByText('🌱 음식을 찾지 못했어요.',{exact:false}).waitFor();
    assert.equal((await calls(page)).some(p=>p==='/foods/estimate'),false,'YOLO failure must not call the LLM');
    assert.equal(await page.getByLabel('음식명',{exact:true}).count(),1,'Failure opens one manual entry');
    await page.getByRole('button',{name:'직접 입력하기',exact:false}).click();
    assert.equal(await page.getByLabel('음식명',{exact:true}).count(),1,'Reuse the blank entry');
    await page.getByLabel('음식명',{exact:true}).fill('목록에 없는 음식');
    assert.equal(await page.locator('.recorder-estimate').count(),0,'No food LLM button may be rendered');
    await page.getByText('영양 정보 수정',{exact:true}).click();
    await page.getByLabel('칼로리 (kcal)',{exact:true}).fill('300');
    assert.equal((await calls(page)).some(p=>p==='/foods/estimate'),false);
    await page.screenshot({path:`.runtime-logs/meal-recorder-manual-${width}.png`,fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.getByRole('button',{name:'식단 기록하기'}).click();
    assert.equal((await saved(page)).items[0].nutrition.cal,300);
    await page.getByRole('button',{name:'저장한 식단 수정'}).click();
    await page.getByLabel('음식명',{exact:true}).fill('수정한 음식');
    await page.getByText('영양 정보 수정',{exact:true}).click();
    await page.getByLabel('칼로리 (kcal)',{exact:true}).fill('350');
    await page.getByLabel('식사 시간').fill('18:45');
    await page.getByRole('button',{name:'변경 내용 저장'}).click();
    await page.waitForFunction(()=>document.querySelector('[data-testid=saved]').textContent.includes('수정한 음식'));
    assert.equal((await saved(page)).items[0].nutrition.cal,350);
    assert.equal((await saved(page)).meal_time,'18:45');
    await page.goto(`${base}/tests/meal-recorder.html`);
    await analyze(page);
    await page.getByLabel('음식 검색',{exact:true}).fill('missing');
    await page.getByRole('button',{name:'검색',exact:true}).click();
    await page.getByText('검색 결과가 없어요. 직접 입력해서 기록할 수 있어요.').waitFor();
    await page.getByRole('button',{name:'직접 입력하기',exact:false}).click();
    await page.getByRole('button',{name:'식단 기록하기'}).click();
    assert.equal((await saved(page)).items[0].nutrition.cal,null);
    await page.goto(`${base}/tests/meal-recorder.html`);
    await page.locator('input[type=file]').setInputFiles(file);
    assert.equal(await page.getByRole('button',{name:'사진만 저장',exact:true}).isVisible(),false);
    await page.getByText('사진 기록 옵션',{exact:true}).click();
    await page.getByRole('button',{name:'사진만 저장',exact:true}).click();
    await page.getByTestId('saved').waitFor();
    assert.equal((await saved(page)).analysis_status,'skipped');
    assert.equal((await saved(page)).items.length,0);
    await page.goto(`${base}/tests/meal-recorder.html`);
    await analyze(page);
    await page.getByLabel('음식 검색',{exact:true}).fill('순대국');
    await page.getByRole('button',{name:'검색',exact:true}).click();
    const result=page.getByRole('button',{name:'순대국',exact:false});
    await result.click();
    assert.equal(await page.getByLabel('음식명',{exact:true}).inputValue(),'','Single click only selects a result');
    if(width===390)await page.getByRole('button',{name:'선택한 음식 적용'}).click();
    else await result.dblclick();
    assert.equal(await page.getByLabel('음식명',{exact:true}).count(),1,'Search selection replaces the blank entry');
    assert.equal(await page.getByLabel('섭취량 (인분)',{exact:true}).inputValue(),'1');
    assert.equal(await page.locator('.recorder-food-meta select').count(),0,'No gram/ml dropdown');
    assert.equal(await page.locator('.recorder-results').count(),0,'Hide search results after applying');
    assert.equal(await page.getByLabel('칼로리 (kcal)',{exact:true}).isVisible(),false);
    await page.getByLabel('섭취량 (인분)',{exact:true}).fill('0.5');
    await page.waitForFunction(()=>document.querySelector('input[aria-label="칼로리 (kcal)"]')?.value==='200');
    await page.getByRole('button',{name:'음식 1 인분 늘리기'}).click();
    await page.waitForFunction(()=>document.querySelector('input[aria-label="칼로리 (kcal)"]')?.value==='400');
    await page.getByLabel('섭취량 (인분)',{exact:true}).fill('1.5');
    await page.waitForFunction(()=>document.querySelector('input[aria-label="칼로리 (kcal)"]')?.value==='600');
    await page.screenshot({path:`.runtime-logs/meal-recorder-selected-${width}.png`,fullPage:true});
    await page.getByRole('button',{name:'식단 기록하기'}).click();
    await page.getByTestId('saved').waitFor();
    assert.equal((await saved(page)).items[0].reference_food_id,'fixture');
    assert.equal((await saved(page)).items[0].amount,1.5);
    assert.equal((await saved(page)).items[0].amount_unit,'serving');
    await page.goto(`${base}/tests/meal-recorder.html?low`);
    await analyze(page);
    await page.waitForFunction(()=>document.querySelector('input[aria-label="칼로리 (kcal)"]')?.value==='400');
    await page.getByRole('button',{name:'다른 후보',exact:true}).click();
    await page.waitForFunction(()=>document.querySelector('input[aria-label="칼로리 (kcal)"]')?.value==='280');
    assert.equal(await page.getByLabel('섭취량 (인분)',{exact:true}).inputValue(),'1');
    await page.goto(`${base}/tests/meal-recorder.html?low`);
    await analyze(page);
    await page.getByRole('button',{name:'다른 음식이에요 · 검색',exact:true}).click();
    await page.getByLabel('음식 검색',{exact:true}).fill('순대국');
    await page.getByRole('button',{name:'검색',exact:true}).click();
    await page.getByRole('button',{name:'순대국',exact:false}).dblclick();
    assert.equal(await page.getByLabel('음식명',{exact:true}).count(),1,'Replace the original YOLO item, never append it');
    assert.equal(await page.getByRole('button',{name:'다른 후보',exact:true}).count(),0,'Remove original candidates after replacement');
    await page.getByRole('button',{name:'음식 1 삭제',exact:true}).click();
    assert.equal(await page.getByLabel('음식명',{exact:true}).count(),0);
    assert.equal((await calls(page)).some(p=>p==='/foods/estimate'),false);
    assert.deepEqual(errors,[]);
    console.log(`PASS ${width}px: explicit YOLO button, automatic fallback form, no food LLM requests, edit/delete, photo-only secondary, no overflow`);
    await page.close();
  }
}finally{await browser.close();}
